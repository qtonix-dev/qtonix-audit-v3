/**
 * GET /api/leads/missed-activities — scheduled calls and tasks that blew past
 * their agreed time by more than an hour without being completed.
 *
 * Managers and admins use this to see who is repeatedly missing commitments;
 * an agent sees only their own, so it doubles as a personal catch-up list.
 * Declared before '/:id' so "missed-activities" isn't read as a lead id.
 */
router.get('/missed-activities', requireAuth, async (req, res, next) => {
  try {
    const where = await visibilityWhere(req.user);
    const leads = await Lead.findAll({ where });
    const now = Date.now();
    const GRACE = 60 * 60 * 1000; // one hour past the agreed time
    // The CRM went live on 3 Aug 2026. Anything due before that is pre-launch
    // noise (migrated/backfilled data) and must never show as a missed
    // commitment. Activities, status changes and email history are untouched;
    // this only affects what the missed-commitments view computes.
    const GO_LIVE = new Date('2026-08-03T00:00:00Z').getTime();
    const items = [];
    const byOwner = {};

    for (const l of leads) {
      if (l.status === 'callback') continue;
      const dismissed = Array.isArray(l.dismissedMissed) ? l.dismissedMissed : [];

      // Unsubmitted first-reply draft: a pre-sales lead whose agent hasn't
      // submitted the first draft within 24h of the lead entering the system.
      // Cleared once EITHER a draft has been submitted (firstDraftAt) OR the
      // owner marked the first reply handled themselves (firstReplyDoneAt).
      const isPreSales = /re-?\s*sales|presales/i.test(String(l.leadSource || ''));
      const enteredAt0 = new Date(l.createdAt).getTime();
      const firstReplyHandled = !!l.firstDraftAt || !!l.firstReplyDoneAt || !!l.firstDraft;
      if (isPreSales && !firstReplyHandled && l.status !== 'converted' && !dismissed.includes(`draft-${l.id}`) && enteredAt0 >= GO_LIVE) {
        const enteredAt = enteredAt0;
        if (!Number.isNaN(enteredAt) && now > enteredAt + 24 * 60 * 60 * 1000) {
          const dueAt = new Date(enteredAt + 24 * 60 * 60 * 1000).toISOString();
          items.push({
            leadId: l.id, leadName: `${l.firstName || ''} ${l.lastName || ''}`.trim(),
            ownerId: l.ownerId, ownerName: l.ownerName,
            activityId: `draft-${l.id}`, kind: 'draft', title: 'First-reply draft not submitted',
            dueAt, hoursLate: Math.max(0, Math.round((now - enteredAt - 24 * 3600000) / 3600000)),
            status: 'open', resolved: false,
          });
          byOwner[l.ownerId] = byOwner[l.ownerId] || { ownerId: l.ownerId, ownerName: l.ownerName, missed: 0, stillOpen: 0 };
          byOwner[l.ownerId].missed++; byOwner[l.ownerId].stillOpen++;
        }
      }

      for (const a of (l.activities || [])) {
        const dueAt = a.kind === 'call'
          ? (a.date ? `${a.date}T${a.time || '09:00'}` : '')
          : (a.dueDate ? `${a.dueDate}T17:00` : '');
        if (!dueAt) continue;
        const due = new Date(dueAt).getTime();
        if (Number.isNaN(due)) continue;
        if (due < GO_LIVE) continue; // pre-launch, don't surface as missed

        // Missed = still open past the grace period, or completed late.
        const stillOpen = a.status !== 'done' && now > due + GRACE;
        const doneLate = a.status === 'done' && a.completedLate;
        if (!stillOpen && !doneLate) continue;
        if (dismissed.includes(String(a.id))) continue; // admin cleared this one

        items.push({
          leadId: l.id, leadName: `${l.firstName || ''} ${l.lastName || ''}`.trim(),
          ownerId: l.ownerId, ownerName: l.ownerName,
          activityId: a.id, kind: a.kind, title: a.title,
          dueAt, hoursLate: Math.max(0, Math.round((now - due) / 3600000)),
          status: a.status, resolved: a.status === 'done',
        });
        byOwner[l.ownerId] = byOwner[l.ownerId] || { ownerId: l.ownerId, ownerName: l.ownerName, missed: 0, stillOpen: 0 };
        byOwner[l.ownerId].missed++;
        if (stillOpen) byOwner[l.ownerId].stillOpen++;
      }
    }

    items.sort((a, b) => new Date(b.dueAt) - new Date(a.dueAt));
    res.json({
      total: items.length,
      stillOpen: items.filter((i) => !i.resolved).length,
      items: items.slice(0, 100),
      byOwner: Object.values(byOwner).sort((a, b) => b.missed - a.missed),
    });
  } catch (e) { next(e); }
});

