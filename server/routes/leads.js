/** POST /api/leads/bulk — create many leads at once (CSV/Excel import).
    Body: { rows: [ {firstName, lastName, website, email, ...}, ... ] }.
    Each row is validated lightly; rows without a first name are skipped and
    reported. Owner defaults to the importing user unless they're admin/manager
    and supply a valid ownerId per row. */
router.post('/bulk', requireAuth, async (req, res, next) => {
  try {
    // Importing a sheet creates records in bulk and is easy to get wrong, so
    // it stays with admins and lead managers — the two roles whose job is
    // getting leads into the system. Sellers work the leads they are given.
    if (req.user.role !== 'admin' && req.user.role !== 'leadmanager') {
      return res.status(403).json({ error: 'Only an admin or lead manager can import leads.' });
    }
    const rows = Array.isArray(req.body && req.body.rows) ? req.body.rows : [];
    if (!rows.length) return res.status(400).json({ error: 'No rows to import.' });
    if (rows.length > 2000) return res.status(400).json({ error: 'Please import at most 2000 rows at a time.' });

    let created = 0;
    const skipped = [];
    const seenDomains = new Set(); // catch duplicates within this same batch too
    for (let i = 0; i < rows.length; i++) {
      const b = rows[i] || {};
      if (!b.firstName || !String(b.firstName).trim()) { skipped.push({ row: i + 1, reason: 'missing first name' }); continue; }
      const owner = await resolveOwner(req.user, b.ownerId);
      if (!owner) { skipped.push({ row: i + 1, reason: 'no valid lead owner (agent/manager) specified' }); continue; }
      // A website belongs to exactly one lead. Skip rows whose domain already
      // exists (in the DB or earlier in this same file) and report why.
      const rowDomain = toDomain(b.website);
      if (rowDomain) {
        if (seenDomains.has(rowDomain)) { skipped.push({ row: i + 1, reason: `duplicate website in this file (${rowDomain})` }); continue; }
        const existing = await findDuplicateByDomain(Lead, b.website);
        if (existing) { skipped.push({ row: i + 1, reason: `duplicate website — already owned by ${existing.ownerName || 'another agent'}` }); continue; }
        seenDomains.add(rowDomain);
      }
      try {
        await Lead.create({
          ownerId: owner.id, ownerName: owner.name,
          ownerTeam: owner.team || 'Bhubaneswar', ownerShift: owner.shift || 'Morning',
          firstName: String(b.firstName).slice(0, 120),
          lastName: String(b.lastName || '').slice(0, 120),
          website: nakedWebsite(b.website),
          domain: toDomain(b.website),
          email: String(b.email || '').slice(0, 180),
          secondaryEmail: String(b.secondaryEmail || '').slice(0, 180),
          mobile: String(b.mobile || '').slice(0, 40),
          phone: String(b.phone || '').slice(0, 40),
          leadSource: String(b.leadSource || '').slice(0, 60),
          generatedBy: String(b.generatedBy || '').slice(0, 120),
          status: String(b.status || 'new').slice(0, 40),
          servicesInterested: Array.isArray(b.servicesInterested) ? b.servicesInterested.slice(0, 30)
            : (b.servicesInterested ? String(b.servicesInterested).split(/[;|]/).map((x) => x.trim()).filter(Boolean) : []),
          tags: Array.isArray(b.tags) ? b.tags.slice(0, 30)
            : (b.tags ? String(b.tags).split(/[;|]/).map((x) => x.trim()).filter(Boolean) : ['New Lead']),
          country: String(b.country || '').slice(0, 80),
          city: String(b.city || '').slice(0, 120),
          timezone: String(b.timezone || '').slice(0, 80),
          additionalInfo: String(b.additionalInfo || '').slice(0, 10000),
          lastActivityAt: new Date(),
          timeline: [{ type: 'created', text: 'Lead imported', time: new Date().toISOString(), author: req.user.name }],
        });
        created++;
      } catch (e) { skipped.push({ row: i + 1, reason: e.message }); }
    }
    await AuditLog.create({ userId: req.user.id, userName: req.user.name, action: 'lead.bulk_import', target: `${created} leads`, ip: req.ip });
    res.status(201).json({ created, skipped });
  } catch (e) { next(e); }
});

/** GET /api/leads/converted — leads with status 'converted'. Managers and
    admins only. Manager sees conversions within their scope; admin sees all.
    Declared before /:id so "converted" isn't captured as an id. */
// ---------------------------------------------------------------------------
// GET /api/leads/dashboard — metrics + leaderboard for the current user's
// visibility scope. Sales are summed from Closed Won deals converted to USD via
// admin-maintained FX rates, within the current calendar month.
// ---------------------------------------------------------------------------
router.get('/dashboard', requireAuth, async (req, res, next) => {
  try {
    const { User, Settings } = require('../models');
    const settings = await Settings.findOne({ where: { singleton: 'settings' } });
    const fx = (settings && settings.crmConfig && settings.crmConfig.fxRates) || { USD: 1 };
    const toUsd = (amount, currency) => { const rate = fx[currency] || 1; return rate ? Number(amount || 0) / rate : Number(amount || 0); };

    const where = await visibilityWhere(req.user);
    const leads = await Lead.findAll({ where });

    const now = new Date();
    const startOfDay = new Date(now.getFullYear(), now.getMonth(), now.getDate());
    const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1);
    const in3d = new Date(Date.now() - 3 * 24 * 60 * 60 * 1000);

    // Load users up-front so we know each lead owner's role while tallying.
    // Admin-owned sales are deliberately kept out of company totals and out of
    // the leaderboard that agents/managers see (admins run demo/test data);
    // they're only surfaced back to admins themselves.
    const owners = await User.findAll({ attributes: ['id', 'name', 'role', 'jobType', 'targets', 'managerId', 'avatar', 'active', 'archived'] });
    const roleById = {};
    owners.forEach((u) => { roleById[u.id] = u.role; });
    const viewerIsAdmin = req.user.role === 'admin';
    // Admin-owned deals are normally kept out of company totals and the
    // leaderboard, because admins run test and demo data that would otherwise
    // distort what agents and managers see. An admin looking at their own
    // dashboard, however, wants the truth with nothing hidden — so for an admin
    // viewer nothing is excluded at all.
    const isAdminOwned = (ownerId) => !viewerIsAdmin && roleById[ownerId] === 'admin';

    let totalLeads = 0, generatedToday = 0, assignedToday = 0, untouched = 0;
    let salesThisMonthUsd = 0, convertedThisMonth = 0;
    let awaitingUsd = 0; // won deals whose installments aren't collected yet
    let pipelineUsd = 0; // open (not won/lost) deal value in USD, motivational
    let newSalesUsd = 0, crossSalesUsd = 0, newSalesCount = 0, crossSalesCount = 0;
    // Parallel tally that always excludes admin-owned deals. An admin viewer
    // sees both: the company figure (everything, including their own test and
    // house accounts) and the team figure (what agents and managers actually
    // brought in) — so the two can be told apart at a glance.
    let teamSalesUsd = 0, teamNewSalesUsd = 0, teamCrossSalesUsd = 0;
    let teamNewCount = 0, teamCrossCount = 0, teamAwaitingUsd = 0;
    const byOwner = {};
    const ensure = (id, name) => (byOwner[id] = byOwner[id] || { ownerId: id, name, salesUsd: 0, newSalesUsd: 0, crossSalesUsd: 0, conversions: 0, leads: 0, transfersToday: 0, leadsGeneratedMonth: 0, leadsGeneratedToday: 0 });
    const genTodayList = [], assignedTodayList = [], untouchedList = [];
    const awaitingList = [];

    // Lead-generation analytics. We split by leadSource so the dashboard can
    // show pre-sales vs cold-calling contribution, and bucket by day (current
    // month) and by month (last 6) for the trend charts.
    const isPresales = (s) => /pre[\s-]?sales/i.test(String(s || ''));
    const isColdCall = (s) => /cold[\s-]?call/i.test(String(s || ''));
    // Channel classification for the "generated vs assigned" split:
    //  - ASSIGNED sources: the lead came to us (Pre-Sales, Referral, Partner,
    //    Inbound). We were handed it.
    //  - GENERATED sources: we produced it through outbound effort
    //    (Cold Calling, Ads & Marketing). A transferred call-back also counts as
    //    generated (handled separately, since it carries transferredAt).
    const isAssignedSource = (s) => /pre[\s-]?sales|referral|partner|inbound/i.test(String(s || ''));
    const isGeneratedSource = (s) => /cold[\s-]?call|ads?\s*&?\s*marketing|marketing/i.test(String(s || ''));
    let leadsGeneratedMonthTotal = 0, leadsPresalesMonth = 0, leadsColdMonth = 0;
    let leadsAssignedMonthTotal = 0;
    const daysInMonth = new Date(now.getFullYear(), now.getMonth() + 1, 0).getDate();
    const leadDaily = Array.from({ length: daysInMonth }, (_, i) => ({
      day: i + 1, total: 0, presales: 0, cold: 0,
    }));
    const leadMonthly = [];
    for (let i = 5; i >= 0; i--) {
      const ms = new Date(now.getFullYear(), now.getMonth() - i, 1);
      leadMonthly.push({
        month: ms.toLocaleString('en-US', { month: 'short' }), year: ms.getFullYear(),
        start: ms, end: new Date(now.getFullYear(), now.getMonth() - i + 1, 1),
        total: 0, presales: 0, cold: 0,
      });
    }

    // Per shift/branch tally (by closed-won collected USD this month).
    const byShift = {}; // key `${team}·${shift}`

    for (const l of leads) {
      const created = l.createdAt ? new Date(l.createdAt) : null;
      // "Generated" is anchored to the real-world generated date (which equals
      // createdAt for a normal add, and the historical date for a back-dated
      // import). "Assigned/entry" activity is anchored to createdAt further down.
      const genAtMonth = l.generatedAt ? new Date(l.generatedAt) : created;
      ensure(l.ownerId, l.ownerName);
      byOwner[l.ownerId].leads++;

      // Lead generation: generated this month / today, credited to the owner.
      if (genAtMonth && genAtMonth >= startOfMonth) byOwner[l.ownerId].leadsGeneratedMonth++;

      const pres = isPresales(l.leadSource) || isPresales(l.generatedBy);
      const cold = isColdCall(l.leadSource) || isColdCall(l.generatedBy);

      if (genAtMonth && genAtMonth >= startOfMonth) {
        leadsGeneratedMonthTotal++;
        if (pres) leadsPresalesMonth++;
        if (cold) leadsColdMonth++;
        const dIdx = genAtMonth.getDate() - 1;
        if (leadDaily[dIdx]) {
          leadDaily[dIdx].total++;
          if (pres) leadDaily[dIdx].presales++;
          if (cold) leadDaily[dIdx].cold++;
        }
      }
      if (created) {
        for (const b of leadMonthly) {
          if (created >= b.start && created < b.end) {
            b.total++;
            if (pres) b.presales++;
            if (cold) b.cold++;
            break;
          }
        }
      }

      const isConverted = l.status === 'converted';
      const isProspect = l.status === 'callback';
      // Call-back prospects aren't worked leads yet, so they don't count toward
      // the lead total and are never flagged untouched — the 3-day rule doesn't
      // apply until they're transferred.
      if (!isConverted && !isProspect) {
        totalLeads++;
        const last = l.lastActivityAt ? new Date(l.lastActivityAt) : null;
        // A lead with a scheduled future call/task is being handled as agreed —
        // e.g. the customer asked for a call in 15 days — so it must NOT show as
        // untouched even though nothing's happened in the last 3 days. Only flag
        // it when there's no pending future activity to wait on. Back-dated
        // leads DO count — their untouched clock runs from the entry date
        // (createdAt/lastActivityAt), not the historical generated date.
        if (last && last < in3d && !hasPendingFutureActivity(l)) {
          untouched++;
          if (untouchedList.length < 8) untouchedList.push(leadBrief(l));
        }
      }

      // GENERATED vs ASSIGNED is decided by how the lead came in, not by timing:
      //  - GENERATED = we produced it. Either its source is an outbound channel
      //    (Cold Calling / Ads & Marketing), OR it was transferred up from a
      //    call-back (carries transferredAt). The "when" is the transfer date for
      //    a transferred call-back, otherwise the generated date.
      //  - ASSIGNED = it was handed to us via an inbound channel (Pre-Sales,
      //    Referral, Partner, Inbound). The "when" is when it landed with its
      //    owner (assignedAt, falling back to entry).
      const transferredAt = l.transferredAt ? new Date(l.transferredAt) : null;
      const isGenerated = !!transferredAt || isGeneratedSource(l.leadSource);
      const isAssigned = !isGenerated && isAssignedSource(l.leadSource);

      const genWhen = transferredAt || (l.generatedAt ? new Date(l.generatedAt) : created);
      const assignedAt = l.assignedAt ? new Date(l.assignedAt) : created;

      if (isGenerated && genWhen && genWhen >= startOfDay) {
        generatedToday++;
        if (byOwner[l.ownerId]) byOwner[l.ownerId].leadsGeneratedToday++;
        if (genTodayList.length < 12) genTodayList.push({ ...leadBrief(l), kind: 'generated' });
      }
      if (isAssigned && assignedAt && assignedAt >= startOfDay) {
        assignedToday++;
        if (assignedTodayList.length < 12) assignedTodayList.push({ ...leadBrief(l), kind: 'assigned' });
      }
      if (isAssigned && assignedAt && assignedAt >= startOfMonth) leadsAssignedMonthTotal++;

      // Converted THIS MONTH only — guard against leads with a missing or
      // malformed convertedAt (old imports) so the count reflects the current
      // calendar month, not the all-time total.
      if (isConverted && l.convertedAt) {
        const cAt = new Date(l.convertedAt);
        if (!Number.isNaN(cAt.getTime()) && cAt >= startOfMonth) {
          convertedThisMonth++;
          if (byOwner[l.ownerId]) byOwner[l.ownerId].conversions++;
        }
      }

      // Sales = installments actually collected (paid) this month. First paid
      // installment of a lead's first deal = new sale; everything else = cross.
      const wonDeals = (l.deals || []).filter((d) => d.stage === 'closed_won');
      // Open pipeline = deals not yet won or lost (motivational "in progress").
      for (const d of (l.deals || [])) {
        if (d.stage !== 'closed_won' && d.stage !== 'closed_lost') {
          const v = toUsd(d.amount, d.currency);
          pipelineUsd += v;
          byOwner[l.ownerId].pipelineUsd = (byOwner[l.ownerId].pipelineUsd || 0) + v;
          const sk = `${l.ownerTeam}·${l.ownerShift}`;
          byShift[sk] = byShift[sk] || { team: l.ownerTeam, shift: l.ownerShift, salesUsd: 0, pipelineUsd: 0 };
          byShift[sk].pipelineUsd += v;
        }
      }
      // Order deals by wonAt/createdAt so "first deal" is stable.
      wonDeals.sort((a, b) => new Date(a.wonAt || a.createdAt || 0) - new Date(b.wonAt || b.createdAt || 0));
      let leadHasCountedNew = false;
      wonDeals.forEach((d, di) => {
        const insts = (d.installments || []).slice().sort((a, b) => (a.seq || 0) - (b.seq || 0));
        const adminOwned = isAdminOwned(l.ownerId);
        // True regardless of who is viewing — drives the team-only split.
        const ownerIsAdmin = roleById[l.ownerId] === 'admin';
        insts.forEach((it) => {
          // Future cycles of a recurring contract are not a debt owed — they're
          // upcoming revenue the admin manages — so they never count as
          // "awaiting collection". Only part-payment (non-recurring) unpaid
          // installments are genuinely awaiting collection.
          const recurringRepeatInst = !!it.recurring && Number(it.seq || 0) > 1;
          if (!it.paid || !it.paidDate) {
            if (!recurringRepeatInst) {
              if (!ownerIsAdmin) teamAwaitingUsd += toUsd(it.amount, d.currency);
              if (!adminOwned) {
                awaitingUsd += toUsd(it.amount, d.currency);
                // Keep a followup list of who owes what, soonest due first.
                awaitingList.push({
                  leadId: l.id, dealId: d.id, instId: it.id,
                  client: `${l.firstName || ''} ${l.lastName || ''}`.trim() || '(no name)',
                  dealName: d.name, currency: d.currency, amount: Number(it.amount || 0),
                  dueDate: it.dueDate || '', seq: it.seq, ownerName: l.ownerName,
                  overdue: !!(it.dueDate && it.dueDate < new Date().toISOString().slice(0, 10)),
                });
              }
            }
            return;
          }
          const pd = new Date(it.paidDate);
          const usd = toUsd(it.amount, d.currency);
          // classify new vs cross: the very first paid installment of the first
          // deal is a new sale; all others are cross sales.
          const isNew = di === 0 && it.seq === 1 && !leadHasCountedNew;
          if (isNew) leadHasCountedNew = true;
          // Recurring deals: only the FIRST billing cycle (seq 1) credits the
          // agent/manager as their sale. Later recurring cycles are ongoing
          // revenue the admin manages, not new selling work — so they don't
          // count toward any agent/manager/team/company figure. (Non-recurring
          // installments keep crediting the owner as cross-sales as before.)
          const recurringRepeat = !!it.recurring && Number(it.seq || 0) > 1;
          if (pd >= startOfMonth && !recurringRepeat) {
            // Per-owner tally always happens (drives the admin-only leaderboard
            // row); company-wide figures skip admin-owned deals.
            byOwner[l.ownerId].salesUsd += usd;
            if (isNew) byOwner[l.ownerId].newSalesUsd += usd;
            else byOwner[l.ownerId].crossSalesUsd += usd;
            // Team-only split: what agents and managers brought in, never
            // admin-owned deals, whoever is looking.
            if (!ownerIsAdmin) {
              teamSalesUsd += usd;
              if (isNew) { teamNewSalesUsd += usd; teamNewCount++; }
              else { teamCrossSalesUsd += usd; teamCrossCount++; }
            }
            if (!adminOwned) {
              salesThisMonthUsd += usd;
              if (isNew) { newSalesUsd += usd; newSalesCount++; }
              else { crossSalesUsd += usd; crossSalesCount++; }
              const key = `${l.ownerTeam}·${l.ownerShift}`;
              byShift[key] = byShift[key] || { team: l.ownerTeam, shift: l.ownerShift, salesUsd: 0, pipelineUsd: 0 };
              byShift[key].salesUsd += usd;
            }
          }
        });
      });

      // "Call transfers today" now means prospect→lead transfers this owner
      // performed today (F1), not completed calls. Credit the person who did
      // the transfer, which may differ from the current owner — so ensure they
      // have a row even if they own no leads themselves.
      if (l.transferredAt && l.transferredById) {
        const t = new Date(l.transferredAt);
        if (t >= startOfDay) {
          const rec = ensure(l.transferredById, l.transferredByName || 'Unknown');
          rec.transfersToday++;
          rec.transferList = rec.transferList || [];
          if (rec.transferList.length < 10) {
            rec.transferList.push({
              leadId: l.id, leadName: `${l.firstName || ''} ${l.lastName || ''}`.trim(),
              toName: l.ownerName, at: l.transferredAt,
            });
          }
        }
      }
    }

    const targetsById = {}, avatarById = {}, nameById = {};
    owners.forEach((u) => { targetsById[u.id] = u.targets || {}; avatarById[u.id] = u.avatar || null; nameById[u.id] = u.name; });

    const inScope = (u) => {
      if (req.user.role === 'admin') return true;
      if (req.user.role === 'manager') return u.managerId === req.user.id || u.id === req.user.id;
      return u.id === req.user.id;
    };
    owners.forEach((u) => {
      // Seed every in-scope active AGENT and MANAGER, so the whole team appears
      // on the leaderboard even at zero sales. Lead managers are never seeded:
      // they don't own leads or make sales, so they have no place on a sales
      // board. Admins are seeded but filtered out for non-admin viewers below.
      if (u.role === 'leadmanager') return;
      if (u.archived) return; // departed agents never appear on live boards
      if (u.active !== false && inScope(u)) ensure(u.id, u.name);
    });

    const leaderboard = Object.values(byOwner).map((o) => {
      const tg = targetsById[o.ownerId] || {};
      const salesTarget = (tg.sales && tg.sales.enabled) ? Number(tg.sales.monthly || 0) : 0;
      const transferTg = (tg.transfer && tg.transfer.enabled) ? tg.transfer : null;
      const pct = salesTarget > 0 ? Math.min(100, Math.round((o.salesUsd / salesTarget) * 100)) : null;
      const remaining = salesTarget > 0 ? Math.max(0, salesTarget - o.salesUsd) : 0;
      return {
        ...o, avatar: avatarById[o.ownerId] || null,
        role: roleById[o.ownerId] || 'agent',
        salesTarget, pct, remaining, hitTarget: salesTarget > 0 && o.salesUsd >= salesTarget,
        transferDailyTarget: transferTg ? Number(transferTg.daily || 0) : 0,
      };
    })
      // The ranking is an AGENT board for agents and managers: managers and
      // admins are excluded from the competitive list, though the viewer always
      // sees their own row so they can track themselves. An admin viewer sees
      // everyone, unfiltered — EXCEPT lead managers, who never belong on a sales
      // board regardless of who's viewing (they own no leads and make no sales).
      .filter((o) => o.role !== 'leadmanager')
      .filter((o) => viewerIsAdmin || o.role === 'agent' || o.ownerId === req.user.id)
      .sort((a, b) => b.salesUsd - a.salesUsd);

    // ------------------------------------------------------------------
    // Sales leaderboard shown on the dashboard. Who appears depends on the
    // viewer, so everyone gets a fair, motivating comparison:
    //   • Agent   → every agent in the company.
    //   • Manager → every agent + the manager's own row.
    //   • Admin   → everyone who books sales: all agents, all managers, and all
    //               owners/admins (nothing hidden).
    // Sales are computed from ALL leads (not the viewer's scoped set) so the
    // board is company-wide, and count only the first cycle of recurring deals.
    let companyLeaderboard = null;
    try {
      const allLeads = await Lead.findAll({ where: { status: { [Op.ne]: 'release' } }, attributes: ['ownerId', 'ownerName', 'deals', 'status'] });
      const compByOwner = {};
      // Seed every active user who can appear on the board at zero, so a newly
      // added user (with no sales yet this month) still shows up rather than
      // being invisible until their first sale.
      const boardUsers = await User.findAll({ where: { active: true }, attributes: ['id', 'name', 'role'] });
      for (const u of boardUsers) {
        if (u.role === 'leadmanager') continue; // never on a sales board
        compByOwner[u.id] = { ownerId: u.id, name: u.name, salesUsd: 0, conversions: 0 };
      }
      for (const l of allLeads) {
        if (!l.ownerId) continue;
        const rec = compByOwner[l.ownerId] || (compByOwner[l.ownerId] = { ownerId: l.ownerId, name: l.ownerName, salesUsd: 0, conversions: 0 });
        if (l.status === 'converted') rec.conversions++;
        for (let di = 0; di < (l.deals || []).length; di++) {
          const d = l.deals[di];
          if (d.stage !== 'closed_won') continue;
          const insts = (d.installments || []).slice().sort((a, b) => (a.seq || 0) - (b.seq || 0));
          insts.forEach((it) => {
            if (!it.paid || !it.paidDate) return;
            const recurringRepeat = !!it.recurring && Number(it.seq || 0) > 1;
            if (recurringRepeat) return;
            const pd = new Date(it.paidAt || it.paidDate);
            if (pd >= startOfMonth) rec.salesUsd += toUsd(it.amount, d.currency);
          });
        }
      }
      // Which roles belong on the board for this viewer.
      const includeRole = (role) => {
        if (role === 'leadmanager') return false;      // never sell → never on the board
        if (viewerIsAdmin) return true;                // admin sees agents + managers + admins
        if (req.user.role === 'manager') return role === 'agent' || false; // + own row appended below
        return role === 'agent';                       // agents see all agents
      };
      companyLeaderboard = Object.values(compByOwner)
        .filter((o) => includeRole(roleById[o.ownerId]))
        .map((o) => {
          const tg = targetsById[o.ownerId] || {};
          const salesTarget = (tg.sales && tg.sales.enabled) ? Number(tg.sales.monthly || 0) : 0;
          // pct is null when no target is set; the frontend must treat null as
          // "no target" (never render "undefined%").
          const pct = salesTarget > 0 ? Math.min(100, Math.round((o.salesUsd / salesTarget) * 100)) : null;
          return {
            ownerId: o.ownerId, name: o.name, salesUsd: Math.round(o.salesUsd),
            conversions: o.conversions || 0,
            avatar: avatarById[o.ownerId] || null, role: roleById[o.ownerId] || 'agent',
            salesTarget, pct, hitTarget: salesTarget > 0 && o.salesUsd >= salesTarget,
          };
        })
        .sort((a, b) => b.salesUsd - a.salesUsd);
      // A manager also sees their own row alongside the agents.
      if (req.user.role === 'manager' && !companyLeaderboard.some((o) => o.ownerId === req.user.id)) {
        const meComp = compByOwner[req.user.id];
        const tg = targetsById[req.user.id] || {};
        const salesTarget = (tg.sales && tg.sales.enabled) ? Number(tg.sales.monthly || 0) : 0;
        const sUsd = Math.round(meComp ? meComp.salesUsd : 0);
        companyLeaderboard.push({
          ownerId: req.user.id, name: req.user.name, salesUsd: sUsd,
          conversions: meComp ? (meComp.conversions || 0) : 0,
          avatar: avatarById[req.user.id] || null, role: 'manager',
          salesTarget, pct: salesTarget > 0 ? Math.min(100, Math.round((sUsd / salesTarget) * 100)) : null,
          hitTarget: salesTarget > 0 && sUsd >= salesTarget,
        });
        companyLeaderboard.sort((a, b) => b.salesUsd - a.salesUsd);
      }
    } catch (e) { companyLeaderboard = null; }

    const transferBoard = leaderboard
      .filter((o) => o.transferDailyTarget > 0 || o.transfersToday > 0)
      .map((o) => ({ ownerId: o.ownerId, name: o.name, avatar: o.avatar, transfersToday: o.transfersToday, dailyTarget: o.transferDailyTarget, pct: o.transferDailyTarget > 0 ? Math.min(100, Math.round((o.transfersToday / o.transferDailyTarget) * 100)) : null, remaining: o.transferDailyTarget > 0 ? Math.max(0, o.transferDailyTarget - o.transfersToday) : 0, transfers: o.transferList || [] }))
      .sort((a, b) => b.transfersToday - a.transfersToday);

    // Company target = every manager's effective team target, PLUS the personal
    // sales targets of agents who report directly to the admin (i.e. not under
    // any manager). An agent is "under a manager" only if their managerId points
    // at an actual manager user.
    const managerIds = new Set(owners.filter((u) => u.role === 'manager').map((u) => u.id));
    const agentSalesByMgr = {};
    owners.forEach((u) => {
      if (u.role === 'agent' && u.managerId && managerIds.has(u.managerId) && u.targets && u.targets.sales && u.targets.sales.enabled) {
        agentSalesByMgr[u.managerId] = (agentSalesByMgr[u.managerId] || 0) + Number(u.targets.sales.monthly || 0);
      }
    });
    let companyTarget = 0;
    // Managers' team targets (override value, or the auto-sum of their agents).
    owners.forEach((u) => {
      if (u.role === 'manager') {
        const t = u.targets && u.targets.team;
        companyTarget += (t && t.override) ? Number(t.monthly || 0) : (agentSalesByMgr[u.id] || 0);
      }
    });
    // Plus agents reporting directly to the admin (no manager, or manager isn't a
    // manager user) — their individual sales targets.
    owners.forEach((u) => {
      if (u.role === 'agent' && !(u.managerId && managerIds.has(u.managerId)) && u.targets && u.targets.sales && u.targets.sales.enabled) {
        companyTarget += Number(u.targets.sales.monthly || 0);
      }
    });

    // The target that applies to THIS viewer's dashboard:
    //  - admin   → whole company
    //  - manager → their team's effective target (override or auto-sum)
    //  - agent   → their own monthly sales target
    let scopeTarget = 0;
    if (req.user.role === 'admin') {
      scopeTarget = companyTarget;
    } else if (req.user.role === 'manager') {
      const meUser = owners.find((u) => u.id === req.user.id);
      const t = meUser && meUser.targets && meUser.targets.team;
      scopeTarget = (t && t.override) ? Number(t.monthly || 0) : (agentSalesByMgr[req.user.id] || 0);
    } else {
      const t = (targetsById[req.user.id] || {}).sales;
      scopeTarget = (t && t.enabled) ? Number(t.monthly || 0) : 0;
    }
    // Achieved against that target. For a manager this is their whole team's
    // collected sales (which already includes any cross-sales they closed
    // themselves on converted clients, since those leads are in their scope).
    const scopeAchieved = salesThisMonthUsd;

    // 6-month trend (collected USD by paid date) within scope. For historical
    // months we also overlay manually-entered figures from Admin → Monthly
    // Targets (the source of truth for migrated/past data), summed across the
    // owners in this dashboard's scope.
    const trendPeriods = [];
    for (let i = 5; i >= 0; i--) {
      const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
      trendPeriods.push(`${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`);
    }
    const scopedOwnerIds = [...new Set([
      ...leads.map((l) => l.ownerId).filter(Boolean),
      ...Object.keys(byOwner).map(Number).filter(Boolean),
    ])];
    const mtRows = scopedOwnerIds.length
      ? await MonthlyTarget.findAll({ where: { period: trendPeriods, userId: scopedOwnerIds } })
      : [];
    const mtAchievedByPeriod = {};
    mtRows.forEach((r) => { mtAchievedByPeriod[r.period] = (mtAchievedByPeriod[r.period] || 0) + Number(r.achievedUsd || 0); });

    const trend = [];
    for (let i = 5; i >= 0; i--) {
      const mStart = new Date(now.getFullYear(), now.getMonth() - i, 1);
      const mEnd = new Date(now.getFullYear(), now.getMonth() - i + 1, 1);
      const period = `${mStart.getFullYear()}-${String(mStart.getMonth() + 1).padStart(2, '0')}`;
      let sum = 0;
      for (const l of leads) {
        for (const d of (l.deals || [])) {
          if (d.stage !== 'closed_won') continue;
          for (const it of (d.installments || [])) {
            if (it.paid && it.paidDate) { const pd = new Date(it.paidDate); if (pd >= mStart && pd < mEnd) sum += toUsd(it.amount, d.currency); }
          }
        }
      }
      // Manual entry for the month takes precedence when present (or when there
      // is no computed sales at all for that month).
      const manual = mtAchievedByPeriod[period] || 0;
      const salesUsd = manual > 0 ? manual : sum;
      trend.push({ month: mStart.toLocaleString('en-US', { month: 'short' }), year: mStart.getFullYear(), salesUsd: Math.round(salesUsd), pct: companyTarget > 0 ? Math.round((salesUsd / companyTarget) * 100) : null });
    }

    // Sales funnel: value + count of deals per pipeline stage, plus the top-of-
    // funnel intake (leads assigned + generated this month). The dashboard shows
    // each stage's amount and how much has been achieved (count) with a %.
    const settingsForStages = await Settings.findOne({ where: { singleton: 'settings' } });
    const dealStages = (settingsForStages && settingsForStages.crmConfig && settingsForStages.crmConfig.dealStages) || [];
    const funnelByStage = {};
    dealStages.forEach((st) => { funnelByStage[st.id] = { id: st.id, label: st.label, color: st.color, count: 0, amountUsd: 0 }; });
    let funnelTotalDeals = 0;
    for (const l of leads) {
      if (l.status === 'callback') continue;
      for (const d of (l.deals || [])) {
        const st = funnelByStage[d.stage];
        if (!st) continue;
        // This-month funnel: only count deals created this month (deals without
        // a createdAt are legacy — fall back to the lead's convertedAt/createdAt
        // so they aren't silently dropped, but still gate on the month).
        const dealDate = new Date(d.createdAt || l.convertedAt || l.createdAt || 0);
        if (Number.isNaN(dealDate.getTime()) || dealDate < startOfMonth) continue;
        st.count++;
        st.amountUsd += toUsd(d.amount, d.currency);
        funnelTotalDeals++;
      }
    }
    const funnelStages = dealStages.map((st) => {
      const f = funnelByStage[st.id];
      return {
        id: st.id, label: st.label, color: st.color,
        count: f.count, amountUsd: Math.round(f.amountUsd),
        // % of all deals that have reached (are sitting at) this stage.
        pct: funnelTotalDeals > 0 ? Math.round((f.count / funnelTotalDeals) * 100) : 0,
      };
    });
    const funnel = {
      leadsAssignedMonth: leadsAssignedMonthTotal,
      leadsGeneratedMonth: leadsGeneratedMonthTotal,
      topOfFunnel: leadsAssignedMonthTotal + leadsGeneratedMonthTotal,
      totalDeals: funnelTotalDeals,
      stages: funnelStages,
    };

    // Top team this month, computed company-wide (like the leaderboard) so
    // agents and managers see the same winning team the admin does — not just
    // their own scope. Tally collected sales this month by the OWNER's team+shift.
    const companyByShift = {};
    try {
      const teamUserById = {};
      const allTeamUsers = await User.findAll({ where: { active: true }, attributes: ['id', 'team', 'shift', 'role'] });
      allTeamUsers.forEach((u) => { teamUserById[u.id] = u; });
      const allLeads2 = await Lead.findAll({ where: { status: { [Op.ne]: 'release' } }, attributes: ['ownerId', 'ownerTeam', 'ownerShift', 'deals'] });
      for (const l of allLeads2) {
        const owner = teamUserById[l.ownerId];
        if (!owner || owner.role === 'admin' || owner.role === 'leadmanager') continue;
        const team = l.ownerTeam || owner.team;
        const shift = l.ownerShift || owner.shift;
        if (!team) continue;
        const key = `${team}||${shift || ''}`;
        const rec = companyByShift[key] || (companyByShift[key] = { team, shift, salesUsd: 0, pipelineUsd: 0 });
        for (const d of (l.deals || [])) {
          if (d.stage !== 'closed_won') continue;
          const insts = (d.installments || []).slice().sort((a, b) => (a.seq || 0) - (b.seq || 0));
          insts.forEach((it) => {
            if (!it.paid || !it.paidDate) return;
            if (it.recurring && Number(it.seq || 0) > 1) return;
            const pd = new Date(it.paidAt || it.paidDate);
            if (pd >= startOfMonth) rec.salesUsd += toUsd(it.amount, d.currency);
          });
        }
      }
    } catch (e) { /* fall back to scoped byShift below */ }

    // Top shift/branch this month. Prefer the company-wide tally; fall back to
    // the viewer-scoped one if the company tally came back empty.
    const shiftSource = Object.keys(companyByShift).length ? companyByShift : byShift;
    const shiftBoard = Object.values(shiftSource).map((s) => ({ ...s, salesUsd: Math.round(s.salesUsd) }))
      .sort((a, b) => (b.salesUsd - a.salesUsd) || ((b.pipelineUsd || 0) - (a.pipelineUsd || 0)));
    const topShift = shiftBoard[0] || null;

    // Enrich the winning team with a manager (photo) or, if the team has no
    // manager, the team members' photos — so the dashboard can show faces just
    // like the top-performer card. Managers are matched by team; members are
    // agents on that team/shift.
    if (topShift) {
      try {
        const teamUsers = await User.findAll({
          where: { active: true, team: topShift.team },
          attributes: ['id', 'name', 'role', 'avatar', 'shift'],
        });
        const mgr = teamUsers.find((u) => u.role === 'manager');
        if (mgr) {
          topShift.manager = { id: mgr.id, name: mgr.name, avatar: mgr.avatar || null };
        } else {
          // No manager → collect member photos (same shift where set).
          const members = teamUsers
            .filter((u) => u.role === 'agent' && (!topShift.shift || !u.shift || u.shift === topShift.shift))
            .slice(0, 5)
            .map((u) => ({ id: u.id, name: u.name, avatar: u.avatar || null }));
          topShift.members = members;
        }
      } catch (e) { /* enrichment is best-effort */ }
    }

    // Top performer of the month = the highest-selling AGENT across the whole
    // company (not just the viewer's scope), so agents and managers see the same
    // leader the admin does. Built from the company-wide sales tally.
    const companyAgents = (companyLeaderboard || []).filter((o) => o.role === 'agent' && o.salesUsd > 0);
    const topPerformer = companyAgents.length
      ? companyAgents.slice().sort((a, b) => (b.salesUsd - a.salesUsd) || ((b.pipelineUsd || 0) - (a.pipelineUsd || 0)))[0]
      : null;
    const topPerformerTied = !!(topPerformer && companyAgents.filter((o) => o.salesUsd === topPerformer.salesUsd).length > 1);

    const meRow = leaderboard.find((o) => o.ownerId === req.user.id) || null;

    // Admin's own leads. Admins can own leads but those are kept out of the
    // competitive leaderboard and company-target math, so this box gives the
    // admin the raw figures they need when reconciling numbers manually.
    let adminOwnLeads = null;
    if (viewerIsAdmin) {
      const myId = Number(req.user.id);
      const mine = leads.filter((l) => Number(l.ownerId) === myId && l.status !== 'callback');
      adminOwnLeads = {
        total: mine.length,
        assignedToday: mine.filter((l) => { const a = l.assignedAt || l.createdAt; return a && new Date(a) >= startOfDay; }).length,
        assignedMonth: mine.filter((l) => { const a = l.assignedAt || l.createdAt; return a && new Date(a) >= startOfMonth; }).length,
      };
    }

    // "Today's leads" shows the most recently added leads across everyone the
    // viewer can see (admin → all; manager → their agents; agent → own), newest
    // first by entry timestamp — not just leads that qualify as generated or
    // assigned today. Call-backs and (for non-admin viewers) admin-owned test
    // leads are excluded, matching the rest of the dashboard.
    const recentlyAdded = leads
      .filter((l) => l.status !== 'callback' && !isAdminOwned(l.ownerId))
      .slice()
      .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
      .slice(0, 12)
      .map((l) => {
        const transferredAt = l.transferredAt ? new Date(l.transferredAt) : null;
        const isGen = !!transferredAt || isGeneratedSource(l.leadSource);
        return { ...leadBrief(l), kind: isGen ? 'generated' : 'assigned', at: l.createdAt };
      });

    // Pre-sales team performance (admin dashboard only). Mirrors the lead-manager
    // dashboard: pre-sales leads attributed to each configured member via
    // "generated by", counted this month against their monthly target.
    let presalesTeam = null;
    if (viewerIsAdmin) {
      const team = normalisePresalesTeam(settings && settings.crmConfig && settings.crmConfig.presalesTeam);
      if (team.length) {
        const normG = (s) => String(s || '').trim();
        const stats = {};
        for (const m of team) stats[m.name] = { name: m.name, monthlyTarget: m.monthlyTarget || 0, today: 0, month: 0, total: 0 };
        for (const l of leads) {
          if (!isPresales(l.leadSource)) continue;
          const g = normG(l.generatedBy);
          if (!g || !(g in stats)) continue;
          const genAt = l.generatedAt ? new Date(l.generatedAt) : (l.createdAt ? new Date(l.createdAt) : null);
          if (!genAt) continue;
          stats[g].total++;
          if (genAt >= startOfMonth) stats[g].month++;
          if (genAt >= startOfDay) stats[g].today++;
        }
        const members = Object.values(stats)
          .map((t) => ({ ...t, pct: t.monthlyTarget > 0 ? Math.round((t.month / t.monthlyTarget) * 100) : null }))
          .sort((a, b) => b.month - a.month);
        presalesTeam = {
          members,
          teamMonth: members.reduce((s, m) => s + m.month, 0),
          teamToday: members.reduce((s, m) => s + m.today, 0),
          teamMonthlyTarget: members.reduce((s, m) => s + (m.monthlyTarget || 0), 0),
        };
      }
    }

    res.json({
      role: req.user.role,
      metrics: {
        totalLeads, generatedToday, assignedToday, untouched,
        salesThisMonthUsd: Math.round(salesThisMonthUsd), convertedThisMonth,
        pipelineUsd: Math.round(pipelineUsd),
        awaitingUsd: Math.round(awaitingUsd),
        newSalesUsd: Math.round(newSalesUsd), crossSalesUsd: Math.round(crossSalesUsd),
        newSalesCount, crossSalesCount,
        companyTarget: Math.round(companyTarget),
        companyPct: companyTarget > 0 ? Math.round((salesThisMonthUsd / companyTarget) * 100) : null,
        // Role-aware target for the row-1 box.
        scopeTarget: Math.round(scopeTarget),
        scopeAchieved: Math.round(scopeAchieved),
        scopePct: scopeTarget > 0 ? Math.round((scopeAchieved / scopeTarget) * 100) : null,
        scopeRemaining: scopeTarget > 0 ? Math.max(0, Math.round(scopeTarget - scopeAchieved)) : 0,
        generatedTarget: targetForToday(targetsById[req.user.id], 'transfer'),
        // Team-wide lead generation (within the viewer's visibility scope).
        leadsGeneratedMonth: leadsGeneratedMonthTotal,
        leadsAssignedMonth: leadsAssignedMonthTotal,
        leadsPresalesMonth: leadsPresalesMonth,
        leadsColdMonth: leadsColdMonth,
        // Admin-only breakdown. `salesThisMonthUsd` above is everything the
        // viewer can see; these are the same figures counting only deals owned
        // by agents and managers, so an admin can separate real team
        // performance from their own house/test accounts. Null for non-admins,
        // who never see admin-owned money in the first place.
        teamSalesUsd: viewerIsAdmin ? Math.round(teamSalesUsd) : null,
        teamNewSalesUsd: viewerIsAdmin ? Math.round(teamNewSalesUsd) : null,
        teamCrossSalesUsd: viewerIsAdmin ? Math.round(teamCrossSalesUsd) : null,
        teamNewSalesCount: viewerIsAdmin ? teamNewCount : null,
        teamCrossSalesCount: viewerIsAdmin ? teamCrossCount : null,
        teamAwaitingUsd: viewerIsAdmin ? Math.round(teamAwaitingUsd) : null,
        adminSalesUsd: viewerIsAdmin ? Math.round(salesThisMonthUsd - teamSalesUsd) : null,
        teamCompanyPct: viewerIsAdmin && companyTarget > 0 ? Math.round((teamSalesUsd / companyTarget) * 100) : null,
      },
      lists: { generatedToday: genTodayList, assignedToday: assignedTodayList, untouched: untouchedList, recentlyAdded },
      presalesTeam,
      adminOwnLeads,
      me: meRow ? {
        salesUsd: meRow.salesUsd, salesTarget: meRow.salesTarget, pct: meRow.pct, remaining: meRow.remaining,
        transfersToday: meRow.transfersToday, transferDailyTarget: meRow.transferDailyTarget,
        newSalesUsd: meRow.newSalesUsd, crossSalesUsd: meRow.crossSalesUsd,
        pipelineUsd: Math.round(meRow.pipelineUsd || 0),
        leadsGeneratedMonth: meRow.leadsGeneratedMonth || 0,
        leadsGeneratedToday: meRow.leadsGeneratedToday || 0,
        leadGenTarget: ((targetsById[req.user.id] || {}).leadGen && (targetsById[req.user.id] || {}).leadGen.enabled)
          ? Number((targetsById[req.user.id] || {}).leadGen.monthly || 0) : 0,
      } : null,
      leaderboard, companyLeaderboard, transferBoard, trend, funnel, shiftBoard, topShift,
      topPerformer, topPerformerTied,
      awaiting: awaitingList.sort((a, b) => String(a.dueDate).localeCompare(String(b.dueDate))).slice(0, 50),
      leadDaily,
      leadMonthly: leadMonthly.map((b) => ({ month: b.month, year: b.year, total: b.total, presales: b.presales, cold: b.cold })),
    });
  } catch (e) { next(e); }
});

// Small helper: a compact lead descriptor for dashboard mini-tables.
function leadBrief(l) {
  return { _id: l.id, name: `${l.firstName || ''} ${l.lastName || ''}`.trim() || '(no name)', website: l.website || '', ownerName: l.ownerName, status: l.status, lastActivityAt: l.lastActivityAt };
}
function targetForToday(targets, kind) {
  if (!targets) return 0;
  if (kind === 'transfer' && targets.transfer && targets.transfer.enabled) return Number(targets.transfer.daily || 0);
  return 0;
}

/** GET /api/leads/celebrations — today's birthdays, work anniversaries, and
 *  wedding anniversaries across all active employees, for a dashboard wish card
 *  shown to everyone. Declared before /:id. */
router.get('/celebrations', requireAuth, async (req, res, next) => {
  try {
    const users = await User.findAll({ where: { active: true }, attributes: ['id', 'name', 'avatar', 'birthday', 'workAnniversary', 'joiningDate', 'anniversary', 'designation'] });
    const now = new Date();
    const mmdd = (d) => { if (!d) return null; const x = new Date(d); return `${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`; };
    const today = `${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
    // 1 → "1st", 2 → "2nd", 3 → "3rd", 4 → "4th", … for the anniversary label.
    const ordinal = (n) => {
      const s = ['th', 'st', 'nd', 'rd'], v = n % 100;
      return n + (s[(v - 20) % 10] || s[v] || s[0]);
    };
    const items = [];
    users.forEach((u) => {
      if (mmdd(u.birthday) === today) items.push({ id: u.id, name: u.name, avatar: u.avatar, type: 'birthday' });
      // Work anniversary is driven by the joining date (falling back to the
      // legacy workAnniversary field). We celebrate on the month+day match and
      // compute which anniversary it is (1st, 2nd, …).
      const joinDate = u.joiningDate || u.workAnniversary;
      if (mmdd(joinDate) === today) {
        const years = joinDate ? (now.getFullYear() - new Date(joinDate).getFullYear()) : 0;
        if (years > 0) {
          items.push({ id: u.id, name: u.name, avatar: u.avatar, type: 'work', years, yearsLabel: ordinal(years) });
        }
      }
      if (mmdd(u.anniversary) === today) items.push({ id: u.id, name: u.name, avatar: u.avatar, type: 'anniversary' });
    });
    res.json({ items });
  } catch (e) { next(e); }
});


