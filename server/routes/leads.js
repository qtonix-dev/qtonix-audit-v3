router.get('/converted', requireAuth, async (req, res, next) => {
  try {
    // Admins and managers always see converted leads (scoped by visibility).
    // An individual agent/manager may also be granted access to their OWN
    // converted clients via the canViewConverted flag.
    const viewer = await User.findByPk(req.user.id);
    const allowed = req.user.role === 'admin' || req.user.role === 'manager' || (viewer && viewer.canViewConverted);
    if (!allowed) {
      return res.status(403).json({ error: 'You do not have access to converted clients.' });
    }
    const where = await visibilityWhere(req.user);
    where.status = 'converted';

    // Period filter: thisMonth | lastMonth | last3 | thisYear | all
    const period = String(req.query.period || 'all');
    const now = new Date();
    let from = null, to = null;
    if (period === 'thisMonth') {
      from = new Date(now.getFullYear(), now.getMonth(), 1);
    } else if (period === 'lastMonth') {
      from = new Date(now.getFullYear(), now.getMonth() - 1, 1);
      to = new Date(now.getFullYear(), now.getMonth(), 1);
    } else if (period === 'last3') {
      from = new Date(now.getFullYear(), now.getMonth() - 2, 1);
    } else if (period === 'thisYear') {
      from = new Date(now.getFullYear(), 0, 1);
    }

    const perPage = Math.min(100, Math.max(1, Number(req.query.perPage) || 20));
    const page = Math.max(1, Number(req.query.page) || 1);

    // The Converted page is driven by WHEN MONEY WAS RECEIVED, not only when a
    // lead was converted. A payment can land in a later month than the
    // conversion, so for a period we include a lead if EITHER it was converted
    // in-window OR any installment was paid in-window. Installments live in a
    // JSON column, so we filter in JS. (For "all", we page in SQL as before.)
    const inWindow = (dLike) => {
      if (!from) return true;
      const d = new Date(dLike);
      if (Number.isNaN(d.getTime())) return false;
      return d >= from && (!to || d < to);
    };
    const paidInWindow = (l) => (l.deals || []).some((d) => (d && d.installments || []).some((it) => it.paid && (it.paidAt || it.paidDate) && inWindow(it.paidAt || it.paidDate)));
    const convertedInWindow = (l) => inWindow(l.convertedAt || l.createdAt);

    let rows, count;
    if (!from) {
      const res2 = await Lead.findAndCountAll({
        where,
        order: [['convertedAt', 'DESC'], ['updatedAt', 'DESC']],
        limit: perPage, offset: (page - 1) * perPage,
      });
      rows = res2.rows; count = res2.count;
    } else {
      // Load all converted leads in scope, filter by the payment/conversion
      // window, then paginate the result set in memory.
      const all = await Lead.findAll({ where, order: [['convertedAt', 'DESC'], ['updatedAt', 'DESC']] });
      const matched = all.filter((l) => convertedInWindow(l) || paidInWindow(l));
      count = matched.length;
      rows = matched.slice((page - 1) * perPage, (page - 1) * perPage + perPage);
    }
    res.json({
      items: rows.map((l) => {
        const o = l.toJSON();
        const deals = Array.isArray(o.deals) ? o.deals : [];
        // Table 1 ("Active / pending") = the client still has something in
        // flight: a deal that isn't closed, or a won deal with unpaid
        // installments. Table 2 ("Completed") = converted with nothing pending
        // (their service is done) — kept for cross-sell follow-up. Legacy Zoho
        // imports (converted, no deals) fall into Table 2.
        const hasOpenDeal = deals.some((d) => d && !['closed_won', 'closed_lost'].includes(d.stage));
        const hasPendingPayment = deals.some((d) => d && d.stage === 'closed_won'
          && Array.isArray(d.installments) && d.installments.some((it) => !it.paid));
        o.openDeal = hasOpenDeal || hasPendingPayment; // Table 1 when true
        o.pendingPayment = hasPendingPayment;
        o.dealCount = deals.length;
        // Renewal info: the soonest renewal date across the client's deals,
        // ignoring stopped recurring contracts. Each paid installment may carry
        // a renewalDate (set at Mark Paid). We surface the earliest upcoming one
        // (or the earliest overall if all are past) so the Converted views can
        // show "next renewal" and build the Upcoming Renewals table.
        const renewDates = [];
        for (const d of deals) {
          if (d && d.recurringStopped) continue; // stopped → no active renewal
          for (const it of (d && d.installments || [])) {
            if (it && it.renewalDate) renewDates.push({ date: it.renewalDate, service: d.service || d.name || '', dealId: d.id });
          }
        }
        renewDates.sort((a, b2) => String(a.date).localeCompare(String(b2.date)));
        const todayStr = new Date().toISOString().slice(0, 10);
        const future = renewDates.find((r) => r.date >= todayStr);
        const nextRenewal = future || renewDates[0] || null; // prefer upcoming, else most-recent past
        o.nextRenewalDate = nextRenewal ? nextRenewal.date : null;
        o.nextRenewalService = nextRenewal ? nextRenewal.service : null;
        o.hasActiveRenewal = renewDates.length > 0;
        return o;
      }),
      total: count, page, perPage,
      pages: Math.max(1, Math.ceil(count / perPage)),
      period,
    });
  } catch (e) { next(e); }
});

