// Resolve owner fields (validate the chosen owner is assignable by this user).
/**
 * Who ends up owning a new lead.
 *
 * Admins, managers and lead managers can hand a lead to someone else — that is
 * the lead manager's whole job, since they key leads in for other people to
 * work and never own anything themselves. Everyone else creates leads for
 * themselves, so the owner is simply the creator.
 */
async function resolveOwner(user, ownerId) {
  let owner;
  if (ownerId && ['admin', 'manager', 'leadmanager'].includes(user.role)) {
    owner = await User.findByPk(ownerId);
  }
  // When no owner is chosen, the creator owns the lead they add — agents always,
  // and admins/managers by default (both can own leads). Lead managers can't own,
  // so they must pick someone.
  if (!owner && (user.role === 'agent' || user.role === 'admin' || user.role === 'manager')) {
    owner = await User.findByPk(user.id);
  }
  // Lead managers never own leads (they only coordinate intake).
  if (owner && owner.role === 'leadmanager') owner = null;
  return owner;
}

/** POST /api/leads — create a single lead. */
router.post('/', requireAuth, async (req, res, next) => {
  try {
    const b = req.body || {};
    if (!b.firstName || !String(b.firstName).trim()) return res.status(400).json({ error: 'First name is required.' });

    // A website belongs to exactly one lead. If the same site (by normalised
    // domain) is already on a lead, block the create and point the user at it.
    // The check is global — a domain is a domain whoever owns it — but whether
    // we hand back an openable link depends on the requester's visibility.
    const newDomain = toDomain(b.website);
    if (newDomain) {
      const dupe = await findDuplicateByDomain(Lead, b.website);
      if (dupe) {
        const visible = await canAccessLead(req.user, dupe);
        // Name the CURRENT LEAD OWNER (not the contact) so the person adding
        // knows who already holds this domain.
        const ownerName = dupe.ownerName || 'another agent';
        return res.status(409).json({
          error: visible
            ? `Duplicate lead — this website already belongs to a lead owned by ${ownerName}.`
            : `Duplicate lead — this website already exists in the system (owned by ${ownerName}).`,
          duplicate: {
            // Only expose the id (for the link) when the user can actually open it.
            _id: visible ? dupe.id : null,
            ownerName,
            name: visible ? (`${dupe.firstName || ''} ${dupe.lastName || ''}`.trim() || '(unnamed lead)') : null,
            visible,
          },
        });
      }
    }

    const owner = await resolveOwner(req.user, b.ownerId);
    if (!owner) {
      return res.status(400).json({ error: 'Choose a lead owner (an agent or manager). Lead managers and admins can’t own leads.' });
    }

    // A call-back prospect (status 'callback') can only be created from a Cold
    // Calling source. For any other source, callback is not a valid status.
    const isCold = /cold\s*call/i.test(String(b.leadSource || ''));
    if (b.status === 'callback' && !isCold) {
      return res.status(400).json({ error: 'Call-backs can only be created from a Cold Calling source.' });
    }

    /**
     * Back-dating captures when the lead was GENERATED in the real world (e.g.
     * migrating historical leads out of Zoho). It sets generatedAt, not
     * createdAt: the lead still "enters the system" now, so createdAt stays as
     * the real entry moment and drives the untouched clock. Capped at two years,
     * never in the future.
     */
    let genDate = null;
    if (b.createdAt && ['admin', 'leadmanager'].includes(req.user.role)) {
      const d = new Date(b.createdAt);
      const twoYearsAgo = new Date(); twoYearsAgo.setFullYear(twoYearsAgo.getFullYear() - 2);
      if (!Number.isNaN(d.getTime()) && d <= new Date() && d >= twoYearsAgo) genDate = d;
    }
    const now = new Date();
    // Back-dated = the generated date differs from the entry (created) date.
    const isBackDated = !!genDate && genDate.toISOString().slice(0, 10) !== now.toISOString().slice(0, 10);

    const lead = await Lead.create({
      ownerId: owner.id,
      ownerName: owner.name,
      ownerTeam: owner.team || 'Bhubaneswar',
      ownerShift: owner.shift || 'Morning',
      firstName: String(b.firstName).slice(0, 120),
      lastName: String(b.lastName || '').slice(0, 120),
      website: nakedWebsite(b.website),
      domain: toDomain(b.website),
      email: String(b.email || '').slice(0, 180),
      secondaryEmail: String(b.secondaryEmail || '').slice(0, 180),
      mobile: String(b.mobile || '').slice(0, 40),
      phone: String(b.phone || '').slice(0, 40),
      leadSource: String(b.leadSource || '').slice(0, 60),
      generatedBy: String(b.generatedBy || '').slice(0, 120),
      generatedFromEmail: String(b.generatedFromEmail || '').slice(0, 180),
      status: String(b.status || 'new').slice(0, 40),
      // Agreed call-back time, when creating a call-back-stage lead.
      callbackAt: (b.status === 'callback' && b.callbackAt) ? new Date(b.callbackAt) : null,
      servicesInterested: Array.isArray(b.servicesInterested) ? b.servicesInterested.slice(0, 30) : [],
      tags: Array.isArray(b.tags) && b.tags.length ? b.tags.slice(0, 30) : ['New Lead'],
      country: String(b.country || '').slice(0, 80),
      city: String(b.city || '').slice(0, 120),
      timezone: String(b.timezone || '').slice(0, 80),
      additionalInfo: String(b.additionalInfo || '').slice(0, 10000),
      // The untouched clock measures from the entry moment, so lastActivityAt
      // starts now even for a back-dated lead — it becomes untouched only if
      // nobody works it for 3 days after it enters the system.
      lastActivityAt: now,
      // Track who generated a call-back prospect so they keep visibility after
      // any later transfer. Only meaningful when the creator is the owner.
      generatedById: (b.status === 'callback' && owner.id === req.user.id) ? req.user.id : null,
      // assignedAt drives the 24-hour first-reply rule, which only applies to
      // same-day (non-back-dated) leads — so it also starts at entry.
      assignedAt: now,
      // The real-world origin date (shown as "Lead generated"), and the flag
      // marking whether it differs from the entry date.
      generatedAt: genDate || now,
      backDated: isBackDated,
      // createdAt is always the true entry moment (default) — never the
      // back-date — so the untouched clock and trend charts read entry time.
      // Who keyed it in, as distinct from who owns it.
      enteredById: req.user.id,
      enteredByName: req.user.name,
      timeline: [{
        type: 'created',
        text: isBackDated ? `Lead created (generated ${genDate.toISOString().slice(0, 10)})` : 'Lead created',
        time: now.toISOString(),
        author: req.user.name,
      }],
    });
    await AuditLog.create({ userId: req.user.id, userName: req.user.name, action: 'lead.create', target: lead.website || lead.email, ip: req.ip });
    res.status(201).json(lead.toJSON());
  } catch (e) { next(e); }
});

/** PATCH /api/leads/:id — edit fields (agents/managers/admin can edit). */
router.patch('/:id', requireAuth, async (req, res, next) => {
  try {
    const lead = await Lead.findByPk(req.params.id);
    if (!lead) return res.status(404).json({ error: 'Lead not found.' });
    if (!(await canAccessLead(req.user, lead))) return res.status(403).json({ error: 'You do not have access to this lead.' });
    const b = req.body || {};
    const author = req.user.name;

    // Owner reassignment (admin/manager only)
    if (b.ownerId && b.ownerId !== lead.ownerId && ['admin', 'manager', 'leadmanager'].includes(req.user.role)) {
      const owner = await resolveOwner(req.user, b.ownerId);
      if (!owner) return res.status(400).json({ error: 'That owner isn’t valid — pick an agent or manager.' });
      lead.ownerId = owner.id; lead.ownerName = owner.name;
      lead.ownerTeam = owner.team || lead.ownerTeam; lead.ownerShift = owner.shift || lead.ownerShift;
      pushTimeline(lead, 'owner', `Owner changed to ${owner.name}`, author);
      lead.assignedAt = new Date();
    }
    if (b.status !== undefined && b.status !== lead.status) {
      const newStatus = String(b.status).slice(0, 40);
      // "callback" is the reserved early funnel stage (the Call Backs section),
      // not a status a worked lead can move to. Once a call-back has been
      // transferred into the lead funnel it can never go back. Reject any attempt
      // to set a lead's status to callback from here.
      if (newStatus === 'callback' && lead.status !== 'callback') {
        return res.status(400).json({ error: 'A lead can’t be moved back to Call Backs. Use the "Follow up" status instead.' });
      }
      // A lead can only be released if it's "clean" — not converted and with no
      // deals attached. Converted clients and any lead carrying a deal (open or
      // won) must stay in the CRM so revenue and history aren't lost.
      if (newStatus === 'release') {
        if (lead.status === 'converted') {
          return res.status(400).json({ error: 'A converted client can’t be released.' });
        }
        if (Array.isArray(lead.deals) && lead.deals.length > 0) {
          return res.status(400).json({ error: 'This lead has deals attached and can’t be released. Remove the deals first, or keep the lead.' });
        }
      }
      pushTimeline(lead, 'status', `Status changed to "${newStatus}"`, author);
      // Keep convertedAt in sync so the lead lands on the Converted tab.
      if (newStatus === 'converted' && lead.status !== 'converted') {
        lead.convertedAt = lead.convertedAt || new Date();
      } else if (newStatus !== 'converted' && lead.status === 'converted') {
        lead.convertedAt = null; // conversion undone
      }
      lead.status = newStatus;
    }
    const simple = ['firstName', 'lastName', 'email', 'secondaryEmail', 'mobile', 'phone', 'leadSource', 'generatedBy', 'country', 'city', 'timezone', 'additionalInfo'];
    for (const f of simple) if (b[f] !== undefined) lead[f] = String(b[f]).slice(0, 10000);
    if (b.website !== undefined) {
      const newDom = toDomain(b.website);
      // Block changing a lead's website to a domain another lead already owns.
      if (newDom && newDom !== toDomain(lead.website)) {
        const clash = await findDuplicateByDomain(Lead, b.website, lead.id);
        if (clash) {
          const visible = await canAccessLead(req.user, clash);
          return res.status(409).json({
            error: `Duplicate lead — this website already belongs to a lead owned by ${clash.ownerName || 'another agent'}.`,
            duplicate: { _id: visible ? clash.id : null, ownerName: clash.ownerName || 'another agent', visible },
          });
        }
      }
      lead.website = nakedWebsite(b.website);
      lead.domain = newDom;
    }
    if (b.servicesInterested !== undefined) { lead.servicesInterested = Array.isArray(b.servicesInterested) ? b.servicesInterested.slice(0, 30) : []; lead.changed('servicesInterested', true); }
    if (b.tags !== undefined) { lead.tags = Array.isArray(b.tags) ? b.tags.slice(0, 30) : []; lead.changed('tags', true); }

    lead.lastActivityAt = new Date();
    await lead.save();
    res.json(lead.toJSON());
  } catch (e) { next(e); }
});

